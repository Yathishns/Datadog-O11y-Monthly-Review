"""Prompt files: the aggregated tables plus a strict output contract, for the consultant who prefers to draw a diagram or
polish prose with an LLM (Glean, ChatGPT, Copilot). Only aggregates leave the machine: identifiers inside resource names are
masked when prompts.mask_resources is true; service, host and dependency names (internal host names and hosts named by IP
address included) are printed as they appear in the exports; no raw spans and no timestamps below the minute. Every prompt
file (not the 00-README.md index) ends with the validate command, so whatever comes back is checked before it goes into
the notebook.
"""
import hashlib
import os
import re

from .classify import redact
from .mermaid import AMBER, RED, counted_callers, flagged_hosts, host_colour
from .narrative import LEDGER, n, pct, sec, table

SEV = {"red": "🔴", "amber": "🟠", "info": "🔵"}

CONTRACT = """Mermaid rules (Datadog's renderer is conservative):
- Start with `flowchart TB` or `flowchart LR`; put every label in double quotes; use `<br/>` for a line break inside a label.
- Node ids start with an upper-case letter and are 2-40 letters, digits or underscores (for example `Svc_checkout`, `Db_orders`), never `End`; real names go in the quoted label.
- Every `subgraph Id["title"]` has its own `direction LR` (or TB) line straight after it, and closes with `end`.
- Shapes: `Svc_a["service"]`, `Db_b[("database")]`, `Host_c(["external host"])`. Edges: `Svc_a -->|"label"| Db_b`. Styles: `style Svc_a fill:#ffe0e0,stroke:#c62828,color:#000` (red) or `fill:#fff3cd,stroke:#b8860b,color:#000` (amber).
- One statement per line: declare every node on its own line before any edge or style that uses it; one edge per line with spaces around the arrow; no chained edges, no `&`, no semicolons.
- At most 20 nodes and 40 edges. No classDef, no frontmatter, no markdown inside labels, no xychart/timeline/mindmap.
- Output only the Mermaid code in one ```mermaid fence, nothing else."""

LIMITS = ("`validate --against` compares the numbers of each section with the original notebook: a number added or changed is an error, a number dropped is a warning. "
          "`validate --text` alone only rejects a figure that facts.json cannot produce in any format, so a typo that happens to match another fact passes. "
          "Neither checks a value inside a Mermaid block: read the diagram against the tables before pasting it.")


def inside_prompt_name(svc):
    """File name of the inside-a-request prompt for a service (the notebook's marker names the same file). A name that
    changes when simplified ('claims_api') gets a short digest, so it never shares a file with 'claims-api'."""
    s = str(svc)
    base = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "service"
    if base != s:
        base += "-" + hashlib.sha1(s.encode("utf-8")).hexdigest()[:6]
    return "04-diagram-inside-" + base + ".md"


def _header(F, title):
    sha = F["meta"].get("facts_sha256", "")
    return f"# {title}\n\n*{F['meta']['org'] or F['meta']['org_short']} · {F['meta']['month']} · generated by ddreview {F['meta']['kit_version']}" + (f" · facts.json {sha[:12]}" if sha else "") + "*\n\n"


def _trailer(prose=False):
    if prose:
        check = ("Save the answer as a file and check it before pasting: `python -m ddreview validate <answer.md> --facts facts.json --text --against <notebook.md>`. "
                 "After pasting, validate the notebook itself: `python -m ddreview validate <notebook.md> --facts facts.json`.")
    else:
        check = "After pasting the diagram into the notebook, validate the notebook: `python -m ddreview validate <notebook.md> --facts facts.json` (it lints every Mermaid block)."
    return "\n\n---\n" + check + "\n" + LIMITS + "\n"


def mask_text(s, mask):
    """Redact identifiers inside code spans only, so prose apostrophes are untouched."""
    return re.sub(r"`([^`]*)`", lambda m: "`" + redact(m.group(1)) + "`", s) if mask else s


def _fail(F, rate, known=True):
    if not F["coverage"]["failure_signal"] or not known:
        return "not recorded"
    return pct(rate)


def write_all(F, body, cfg, out_dir, mask=True):
    os.makedirs(out_dir, exist_ok=True)
    files = {}
    mode = cfg["report"].get("diagrams", "both")
    if mode != "code":
        files["01-diagram-landscape.md"] = landscape_prompt(F, mask, body)
        if any(f["detector"] in ("failing_dependencies", "nonprod_from_prod", "egress_and_telemetry") for f in body):
            files["03-diagram-dependencies.md"] = dependencies_prompt(F, body)
        for f in body:
            if f["diagram"] and f["diagram"].startswith("inside:"):
                svc = f["diagram"].split(":", 1)[1]
                files[inside_prompt_name(svc)] = inside_prompt(F, svc, mask)
    files["10-polish-findings.md"] = polish_prompt(F, body, mask)
    files["11-exec-summary.md"] = exec_summary_prompt(F, body, mask, F.get("healthy") or ())
    if F.get("mom"):
        files["22-month-over-month.md"] = mom_prompt(F, mask)
    files["00-README.md"] = readme(F, sorted(files), mode)
    for name, text in files.items():
        with open(os.path.join(out_dir, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    return sorted(files)


def readme(F, names, mode="both"):
    if mode == "prompt":
        place = {"01-diagram-landscape.md": "paste it in place of the *Service map* marker under *What Datadog sees today*",
                 "03-diagram-dependencies.md": "paste it in place of the *Dependency map* marker in the first dependency finding",
                 "inside": "paste it in place of the *Inside a request* marker in that finding"}
    else:
        place = {"01-diagram-landscape.md": "replace the landscape Mermaid block under *What Datadog sees today*",
                 "03-diagram-dependencies.md": "replace the dependency-map Mermaid block",
                 "inside": "replace the Mermaid block in that finding"}
    purpose = {"01-diagram-landscape.md": ("a service map in Mermaid", place["01-diagram-landscape.md"] + ", then validate the notebook"),
               "03-diagram-dependencies.md": ("the failing-dependencies map", place["03-diagram-dependencies.md"] + ", then validate the notebook"),
               "10-polish-findings.md": ("the findings re-written in a smoother voice, every number kept",
                                         "check the answer with `validate --text --against`, then replace the lead, table, bullets and actions of each finding; keep its diagram, live-graph and 🔎 lines"),
               "11-exec-summary.md": ("a 150-word leadership paragraph", "check it with `validate --text --against`, then put it under the executive summary table"),
               "22-month-over-month.md": ("four sentences on what moved", "check them with `validate --text --against`, then put them under *Since last month*")}
    rows = []
    for name in names:
        if name.startswith("04-diagram-inside-"):
            rows.append([f"`{name}`", "the inside-a-request diagram for that service", place["inside"] + ", then validate the notebook"])
        elif name in purpose:
            rows.append([f"`{name}`", purpose[name][0], purpose[name][1]])
    pie = ("The requests-by-domain pie is drawn only by the generator (diagrams `both` or `code`); there is no prompt for it.\n\n" if mode == "prompt" else "")
    return _header(F, "How to use these prompt files") + """Each file is self-contained: paste it into the LLM of your choice as it is. They hold aggregated tables only
(services, operations, calls, failure rates, p95). Identifiers inside resource names are masked; service, host and
dependency names, including internal host names and hosts named by IP address, appear as they do in the exports. No raw
spans and no timestamps below the minute are included. facts.json and the exports stay on your machine.

""" + table(["File", "Paste it to get", "Then"], rows) + "\n\n" + pie + """The LLM may change wording, order of bullets and diagram layout. It may not change, round, drop or add a number, remove a
qualifier such as "without noise" or "in the 9-minute sample", or add a claim the tables do not support. """ + LIMITS + "\n"


def _colour_rows(F, body, names):
    flagged = flagged_hosts(body)
    rows = []
    for name in names:
        sev = flagged.get(name)
        if sev in ("red", "amber"):
            rows.append([name, sev])
    return rows


def landscape_prompt(F, mask, body=()):
    rows = []
    list_rates = False
    vt = F["window"]["volumes_tier"]
    flagged = flagged_hosts(body)
    for key, d in F["domains"].items():
        if d.get("empty"):
            continue
        tier = d.get("volume_tier", vt)
        req = n(d["requests"]["all"]) + ("" if tier == vt else " (" + F["window"]["phrase"]["services_list" if tier == "services_list" else "sample"].replace("in the ", "") + ")")
        svcs = sorted(d["services"], key=lambda s: (s not in flagged, -F["services"][s]["requests"]["all"], s))
        listed = ", ".join(svcs[:6]) + (f" +{len(svcs) - 6} more" if len(svcs) > 6 else "")
        from .render import NOT_RECORDED, domain_rate_text
        rate_txt, used = domain_rate_text(F, d, name=str)
        rate_txt = "not recorded" if rate_txt == NOT_RECORDED else rate_txt
        list_rates = list_rates or used
        rows.append([d["label"], listed, req, rate_txt, ", ".join(f"{F['services'][s]['tech'] or 'entry service'}" for s in svcs[:3])])
    sp = F["window"]["phrase"]["sample"]
    nonprod_svcs = set((F["coverage"].get("env_scope") or {}).get("nonprod_services", []))
    env_col = bool((F["coverage"].get("env_scope") or {}).get("column"))
    kept = [e for e in F["edges"] if e["from"] not in nonprod_svcs and (e["to"] in F["services"] or e["to"] in F["dependencies"])
            and not (env_col and (F["dependencies"].get(e["to"]) or {}).get("class") in ("nonprod", "public", "telemetry") and not (e.get("prod") or {}).get("calls"))]
    view = lambda e: (dict(e, calls=e["prod"]["calls"], err={"pct": 100.0 * e["prod"]["failed"] / e["prod"]["calls"], "num": e["prod"]["failed"], "den": e["prod"]["calls"]}, p95_s=e["prod"]["p95_s"])
                      if env_col and (F["dependencies"].get(e["to"]) or {}).get("class") in ("nonprod", "public", "telemetry") and (e.get("prod") or {}).get("calls") else e)
    edges = [[x["from"], x["to"], x["kind"], f"{n(x['calls'])} ({sp})", _fail(F, x["err"], x.get("failure_known", True)), sec(x["p95_s"])] for x in map(view, kept[:40])]
    deps = [[name, d["class"] + (f" ({d['marker']})" if d["class"] == "nonprod" and d.get("marker") else ""), f"{n(d['calls'])} ({F['window']['phrase']['services_list'] if d['tier'] == 'services_list' else sp})", _fail(F, d["err"], d.get("failure_known", True)),
             sec(d["p95_s"]), ", ".join(c["service"] for c in d["callers"][:3]) or "unknown"]
            for name, d in sorted(F["dependencies"].items(), key=lambda kv: (kv[0] not in flagged, -kv[1]["calls"], kv[0]))[:25]]
    if len(F["dependencies"]) > 25:
        deps.append([f"+{len(F['dependencies']) - 25} more", "", "", "", "", ""])
    rank_ = {"red": 2, "amber": 1}
    names = [s for d in F["domains"].values() for s in d["services"]] + sorted(F["dependencies"], key=lambda h: (-rank_.get(flagged.get(h), 0), -F["dependencies"][h]["calls"], h))
    colours = _colour_rows(F, body, names)
    folded = set(F["meta"].get("landscape_folded_hosts") or [])      # the flagged hosts the generated map could not fit
    hidden = [c for c in colours if c[0] in F["dependencies"] and c[0] in folded]
    if hidden:
        colours = [c for c in colours if c not in hidden] + [[f"+{len(hidden)} more flagged hosts", "red" if any(c[1] == "red" for c in hidden) else "amber"]]
    colour = ("Style a node red or amber exactly as the Colour table says (the worst finding that names it; a node group takes its worst member's colour); leave every other node plain."
              if colours else "No finding names a service or host, so leave every node plain.")
    out = _header(F, "Draw the service landscape") + ("You are drawing the architecture map for a monthly observability review. Draw a Mermaid `flowchart TB` with one `subgraph` per domain "
                                                       "(each with its own `direction LR`), one node per service, databases as cylinders, external hosts as stadiums, and edges only where "
                                                       f"the tables below show calls. {colour} Keep within 20 nodes: keep every node the Colour table names (if they do not all fit, fold the last flagged hosts into one "
                                                       "\"+N more flagged hosts\" node in the worst colour of what it hides), then the busiest services "
                                                       "of each domain; fold the rest of a domain into one \"+N more services\" node, domains that do not fit into one \"+N more domains\" node in the worst colour "
                                                       "of what it hides, and leave out uncoloured dependencies that do not fit.\n\n")
    out += "**Domains and services** (" + F["window"]["phrase"]["volumes"] + "):\n\n" + table(["Domain", "Services", "Requests", "Failure rate (business)", "Stack"], rows) + "\n\n"
    if list_rates:
        out += "◇ marks a failure rate from the Services list: those services' requests in the sample carry no status code or error flag.\n\n"
    if edges:
        out += "**Observed calls** (from the span sample; each count says its window):\n\n" + table(["From", "To", "Kind", "Calls", "Failure rate", "p95"], edges) + "\n\n"
    if deps:
        out += "**Dependencies** (each count says its window):\n\n" + table(["Host or service", "Class", "Calls", "Failure rate", "p95", "Callers"], deps) + "\n\n"
    if colours:
        out += "**Colour**:\n\n" + table(["Node", "Colour"], colours) + "\n\n"
    return out + CONTRACT + _trailer()


def dependencies_prompt(F, body):
    hosts = []
    for f in body:
        for h in f["subject"].get("hosts", []):
            if h not in hosts and h in F["dependencies"]:
                hosts.append(h)
    T = F["meta"]["thresholds"]
    flagged = flagged_hosts(body)

    def colour(h):
        c = host_colour(F["dependencies"][h], flagged.get(h))
        return "red" if c == RED else ("amber" if c == AMBER else "plain")

    def callers(dep):
        fk = dep.get("failure_known", True)
        def one(c):
            rate = _fail(F, c["err"], c.get("failure_known", fk))
            return f"{c['service']}: " + ("failures not recorded" if rate == "not recorded" else f"{rate} failed") + (f", p95 {sec(c['p95_s'])}" if c.get("p95_s") else "")
        return "; ".join(one(c) for c in counted_callers(F, dep)[:3]) or "unknown"
    more = len(hosts) - 12
    cls = lambda d: d["class"] + (f" ({d['marker']})" if d["class"] == "nonprod" and d.get("marker") else "")
    rows = [[h, cls(F["dependencies"][h]), n(F["dependencies"][h]["calls"]), _fail(F, F["dependencies"][h]["err"], F["dependencies"][h].get("failure_known", True)),
             sec(F["dependencies"][h]["p95_s"]), callers(F["dependencies"][h]), colour(h)] for h in hosts[:12]]
    if more > 0:
        rest = [colour(h) for h in hosts[12:]]
        rows.append([f"+{n(more)} more hosts", "", "", "", "", "", "red" if "red" in rest else ("amber" if "amber" in rest else "plain")])
    bar = LEDGER.add(f"{T['dep_fail_pct']:g} %")
    out = _header(F, "Draw the failing dependencies") + (
        "Here is a table of production services and the hosts they call, with calls, failure rate and p95. Draw a Mermaid `flowchart LR` with one node per host and one node per caller "
        f"(or a single \"Production services\" node when the caller is unknown). Label each caller's edge with that caller's own failure rate and p95 from the Callers column "
        f"(the host's figures only on a \"Production services\" edge) when the host fails above {bar} or answers above "
        f"{sec(T['dep_slow_s'])}, and `production → <marker>` for a non-production host, with the marker shown in brackets in its Class column (for example `production → UAT`). Style each host as the Colour column says. Keep labels under 30 characters. "
        "Draw at most the hosts listed (a last row '+N more hosts' is one node); when host and caller nodes together would pass 20, draw the remaining hosts' callers "
        "as one \"Production services\" node with the host's own figures on its edge.\n\n")
    return out + table(["Host", "Class", "Calls", "Failure rate", "p95", "Callers", "Colour"], rows) + "\n\n" + CONTRACT + _trailer()


def inside_prompt(F, svc, mask):
    a = F["anatomy"].get(svc, {})
    rows = [[k, f"{v['value']:.2f}"] for k, v in a.get("children_per_request", {}).items()]
    sr = (a.get("secret_reads_per_request") or {}).get("value")
    if sr and sr >= F["meta"]["thresholds"]["secret_reads_per_request"] and "secret_store" not in a.get("children_per_request", {}):
        rows.append(["secret_store", f"{sr:.2f}"])
    if a.get("cache_table_queries"):
        rows.append(["cache and lock tables in the database (statements in the whole sample)", str(a["cache_table_queries"])])
    rep = [[r["kind"], r["service"], (redact(r["resource"]) if mask else r["resource"]) + (f" to {r['target']}" if r.get("target") and r["target"] not in r["resource"].lower() else ""),
            f"{r['median']:g}"] for r in a.get("repeated_children", [])]
    T = F["meta"]["thresholds"]
    out = _header(F, f"Draw what happens inside a {svc} request") + (
        f"Draw a Mermaid `flowchart LR`: a request node, then the application node (`{F['services'][svc]['tech'] or 'application'}`), then one node per child kind with the per-request "
        f"ratio on the edge label (for example `~25 statements per request`). Style amber any kind above these thresholds: database {T['db_per_request']:.0f}, HTTP {T['http_per_request']:.0f}, "
        f"cache {T['cache_per_request']:.0f}, secret-store reads {T['secret_reads_per_request']} per request. The notebook already says above the diagram that these are sample ratios ({F['window']['phrase']['sample']}).\n\n")
    out += table(["Child kind", "Per request (sample ratio)"], rows) + "\n\n"
    if rep:
        out += "**Repeated children (N+1 candidates)**:\n\n" + table(["Kind", "Service", "Resource", "Times per typical request"], rep) + "\n\n"
    return out + CONTRACT + _trailer()


_NUMTOK = re.compile(r"(?<![\w/.\-@#:])\d[\d,]*(?:\.\d+)?(?:\s?(?:%|ms|s)(?!\w))?(?![\w/\-:])")


def polish_prompt(F, body, mask):
    out = _header(F, "Polish the findings without touching a number") + (
        "Rewrite each finding below in plain British English for a mixed audience of executives and engineers. Keep every number exactly as written, with its numerator and denominator; "
        "keep every qualifier (\"without noise\", \"in the 9-minute sample\", \"about\"); keep the headings (\"## Finding N — …\"), the severity, the table rows and the order; keep service "
        "and operation names in backticks. Do not add claims the evidence does not support. Return the same sections in the same order, nothing else.\n\n")
    locked, texts = set(), []
    for f in body:
        lead, bullets, actions = mask_text(f["lead"], mask), [mask_text(b, mask) for b in f["bullets"]], [mask_text(a["text"], mask) for a in f["actions"]]
        title = mask_text(f["title"], mask)
        out += f"## {SEV[f['severity']]} Finding {f['number']} — {title}\n\n{lead}\n\n"
        cells = []
        if f["table"] and f["table"]["rows"]:
            rows = [[mask_text(str(c), mask) for c in r] for r in f["table"]["rows"]]
            out += table(f["table"]["columns"], rows) + "\n\n"
            cells = [c for r in rows for c in r]
        for b in bullets:
            out += f"- {b}\n"
        out += "\n**Actions**\n" + "\n".join(f"{i}. {a}." for i, a in enumerate(actions, 1)) + "\n\n"
        texts.append("\n".join([lead] + bullets + actions + cells))
    for tok in _NUMTOK.findall("\n".join(texts)):
        t = tok.strip()
        if re.match(r"^(19|20)\d\d$", t) or (len(t) <= 2 and t.isdigit()):
            continue
        locked.add(t)
    out += "**LOCKED NUMBERS** (must appear unchanged): " + ", ".join(sorted(locked, key=lambda x: (len(x), x))[:150]) + "\n"
    return out + _trailer(prose=True)


def exec_summary_prompt(F, body, mask=True, healthy_rows=()):
    rows = [[str(f["number"]), mask_text(f["summary"]["finding"], mask), f["summary"].get("who", ""), f["severity"], mask_text(f["summary"]["action"], mask)] for f in body]
    rows += [["", mask_text(r["sentence"], mask), r.get("audience", ""), r["status"], r.get("action", "")] for r in healthy_rows]
    out = _header(F, "Write the leadership paragraph") + ("From the executive-summary rows below, write one paragraph of at most 150 words for the leadership team: what is hurting users now, "
                                                           "what is hygiene, and the one decision they need to take this month. Keep every number exactly as written. No bullet points, no new claims. "
                                                           "Start the answer with the heading `## 📌 Executive summary` so it can be checked against that section.\n\n")
    return out + table(["#", "Finding", "Who feels it", "Severity", "Action"], rows) + _trailer(prose=True)


def mom_prompt(F, mask=True):
    m = F["mom"]
    rows = [[mask_text(r["where"], mask), r["metric"], r["then_text"], r["now_text"], r["change_text"]] for r in m["moved"][:12]]
    out = _header(F, "Say what moved since last month") + (f"Write four sentences on what changed between {m['previous']['month']} and {F['meta']['month']}: what closed, what is new, "
                                                            "what got worse, what got better. Keep the numbers exactly as written. Say 'not measured' rather than 'closed' for a "
                                                            "finding listed under Not measured. Start the answer with the heading "
                                                            f"`## 📈 Since last month ({m['previous']['month']})` so it can be checked against that section.\n\n")
    fm = m["findings"]
    mt = lambda xs: ", ".join(mask_text(c["title"], mask) for c in xs)
    by_status = lambda s: [c for c in fm["closed"] if c.get("status") == s]
    out += "Closed: " + (mt(by_status("closed")) or "none") + "\n\nNew: " + (mt(fm["new"]) or "none") + "\n\n"
    for status, text in (("superseded", "Now reported within another finding"), ("below_threshold", "Closed only because a threshold changed (the figure still clears last month's bar)"),
                         ("too_little_traffic", "Too little traffic this month to judge"), ("reclassified", "Reclassified as noise (by design, health check or another noise class)"),
                         ("within_target", "Closed because the operation is within its agreed target now (the target changed)"),
                         ("host_reclassified", "Reclassified by the hosts config while the calls continue"),
                         ("within_noise", "Under the bar this month, within sampling noise (not closed)")):
        if by_status(status):
            out += f"{text}: {mt(by_status(status))}\n\n"
    trend = lambda r: "no comparable figure" if r["direction"] == "new" else r["direction"]
    for key, text in (("persisting", "Persisting"), ("promoted", "Only noted last month, now a finding"), ("demoted", "Persisting but moved to Also noted")):
        if fm.get(key):
            out += f"{text}: " + "; ".join(f"{mask_text(r['title'], mask)} ({r['then_text']} → {r['now_text']}, {trend(r)})" for r in fm[key]) + "\n\n"
    if m.get("thresholds_changed"):
        from .render import _threshold_note
        out += _threshold_note(m["thresholds_changed"]) + "\n\n"
    if m.get("targets_changed"):
        from .render import _targets_note
        out += _targets_note(m["targets_changed"]) + "\n\n"
    if fm.get("unmeasured"):
        out += "Not checked this month (" + "; ".join(sorted({c.get("reason") or "the exports cannot check it" for c in fm["unmeasured"]})) + "): " + mt(fm["unmeasured"]) + "\n\n"
    if fm.get("first_measured"):
        out += "Measured for the first time (" + "; ".join(sorted({c.get("reason") or "last month's export had no status code or error column" for c in fm["first_measured"]})) + "): " + mt(fm["first_measured"]) + "\n\n"
    return out + table(["Where", "Metric", m["previous"]["month"], F["meta"]["month"], "Change"], rows) + _trailer(prose=True)
